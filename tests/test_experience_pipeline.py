"""Four-product orchestrator must detect conflicts before any publication."""
import json
from pathlib import Path

import pytest

from exam_mastery.learning import experience_pipeline as pipeline


def fixture():
    return json.loads(
        (Path(__file__).resolve().parents[1] / "fixtures" / "experience_reference.json")
        .read_text(encoding="utf-8")
    )


def test_preflight_writes_nothing_and_needs_no_course_documents(tmp_path):
    report = pipeline.preflight(fixture(), tmp_path)
    assert report["status"] == "PREFLIGHT_PASS"
    assert report["model_calls"] == 0
    assert not list(tmp_path.iterdir())
    assert report["expected_products"] == [
        "Lehrbuch.pdf", "Arbeitsbuch.pdf", "Anki.apkg", "Interaktiv/index.html"
    ]


@pytest.mark.parametrize("name", [
    "Lehrbuch.pdf", "Arbeitsbuch.pdf", "Anki.apkg", "Interaktiv/index.html"
])
def test_unknown_user_output_prevents_all_writes(tmp_path, name):
    path = tmp_path / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(b"Personal content, not generated by Exam Mastery")
    with pytest.raises(ValueError, match="unmanaged"):
        pipeline.build(fixture(), tmp_path)
    assert path.read_bytes() == b"Personal content, not generated by Exam Mastery"
    assert not (tmp_path / "Lehrbuch.pdf").exists() or name == "Lehrbuch.pdf"


def test_coherent_four_product_dispatch_without_extra_outputs(monkeypatch, tmp_path):
    from exam_mastery.learning import experience_books, experience_anki, interactive_reference
    calls = []

    def books(unit, output_dir):
        calls.append("books")
        for name in ("Lehrbuch.pdf", "Arbeitsbuch.pdf"):
            (Path(output_dir) / name).write_bytes(b"pdf")
        return {"status": "CREATED_OR_UPDATED", "products": ["Lehrbuch.pdf", "Arbeitsbuch.pdf"]}

    def anki(unit, output_dir):
        calls.append("anki")
        (Path(output_dir) / "Anki.apkg").write_bytes(b"apkg")
        return {"status": "CREATED_OR_UPDATED"}

    def interactive(unit, output_dir):
        calls.append("interactive")
        target = Path(output_dir) / "Interaktiv" / "index.html"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text("html", encoding="utf-8")
        return {"status": "CREATED_OR_UPDATED"}

    monkeypatch.setattr(experience_books, "publish", books)
    monkeypatch.setattr(experience_anki, "publish", anki)
    monkeypatch.setattr(interactive_reference, "publish", interactive)
    lesson = fixture()
    result = pipeline.build(lesson, tmp_path)
    assert calls == ["books", "anki", "interactive"]
    assert result["status"] == "READY_FOR_TECHNICAL_REVIEW"
    assert result["academic_status"] == "HUMAN_REVIEW_PENDING"
    assert result["model_calls"] == result["network_calls"] == 0
    assert set(result["products"].values()) == {
        "Lehrbuch.pdf", "Arbeitsbuch.pdf", "Anki.apkg", "Interaktiv/index.html"
    }


@pytest.mark.parametrize("case", [
    "no_cards", "no_interactions", "unknown_model", "invalid_parameters",
])
def test_unpublishable_but_structurally_valid_unit_fails_before_any_write(tmp_path, case):
    """A passed schema check must never authorize a half-published package."""
    from exam_mastery.learning.experience import validate

    lesson = fixture()
    if case == "no_cards":
        lesson["cards"] = []
        lesson["anki_not_applicable_reason"] = "Not an appropriate retrieval target."
        expected = "no Anki cards"
    elif case == "no_interactions":
        lesson["interactions"] = []
        lesson["interaction_not_applicable_reason"] = "No validated simulation available."
        expected = "no interactive model"
    elif case == "unknown_model":
        lesson["interactions"][0]["model_ref"] = "unregistered_model"
        expected = "Unsupported executable model"
    else:
        lesson["interactions"][0]["variants"][0]["parameters"]["values"] = [8, 2]
        expected = "sorted ascending"

    assert validate(lesson)["valid"]
    with pytest.raises(ValueError, match=expected):
        pipeline.build(lesson, tmp_path)
    assert not list(tmp_path.iterdir()), "No publisher may start before preflight completes"


@pytest.mark.parametrize("managed", [".em-state", "Interaktiv"])
def test_symlinked_managed_directories_fail_closed(tmp_path, managed):
    """A symlinked parent could redirect otherwise regular output files."""
    outside = tmp_path.parent / (tmp_path.name + "-external")
    outside.mkdir()
    (tmp_path / managed).symlink_to(outside, target_is_directory=True)
    with pytest.raises(ValueError, match="nonregular managed directory"):
        pipeline.preflight(fixture(), tmp_path)
    assert list(outside.iterdir()) == []
